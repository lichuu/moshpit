import { chromium } from "playwright";
const b = await chromium.launch();
let failed = false;
const log = (ok, msg) => { console.log(ok ? `ok   ${msg}` : `FAIL ${msg}`); if (!ok) failed = true; };
const json = (r, body) => r.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
const p = await ctx.newPage();
await p.route("**/api/vapid", (r) => r.fulfill({ status: 404 })); // no auto-bridge → manual onboarding
await p.route("**/api/pair", (r) => json(r, { deviceId: "d" }));
await p.route("**/api/snapshot", (r) => json(r, { hostId: "test", herdrRunning: true, agents: [], kinds: [] }));
await p.goto("http://127.0.0.1:8188/");
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Next", exact: true }).click();
await p.getByRole("button", { name: "Next", exact: true }).click();
await p.getByRole("button", { name: "Open moshpit" }).click();
await p.waitForTimeout(1500);
await p.evaluate(() => {
  const raw = JSON.parse(localStorage.getItem("moshpit-v1"));
  raw.state.hosts = [{ id: "test", label: "Test", tailnetUrl: "http://127.0.0.1:8188/", demo: false }];
  raw.state.connectedHostId = "test";
  raw.state.herdrRunning = true;
  raw.state.agents = [];
  localStorage.setItem("moshpit-v1", JSON.stringify(raw));
});
await p.reload({ waitUntil: "networkidle" });
await p.waitForTimeout(1500);
const h = p.getByRole("heading", { name: "Waiting for your herd." });
await h.waitFor({ state: "visible", timeout: 8000 });
const box = await h.boundingBox();
const host = await h.locator("xpath=ancestor::div[contains(@class,'flex-1')]").first().boundingBox();
const center = Math.round(box.x + box.width / 2);
const hostCenter = Math.round(host.x + host.width / 2);
log(Boolean(box) && Math.abs(center - hostCenter) < 8, `heading centered in full-width pane (${center}/${hostCenter})`);
log(host.width > 900, `pane is full width (host ${host.width}px of 1280)`);
const svg = await p.locator('div[class*="flex-1"] svg.animate-spin').first().boundingBox();
log(Boolean(svg), "spinner present and animating");
const spinCenter = svg ? Math.round(svg.x + svg.width / 2) : -1;
log(Math.abs(spinCenter - hostCenter) < 8, `spinner centered (${spinCenter}/${hostCenter})`);
await p.screenshot({ path: "check-herd-wait-desktop.png" });
await ctx.close();
await b.close();
process.exit(failed ? 1 : 0);
